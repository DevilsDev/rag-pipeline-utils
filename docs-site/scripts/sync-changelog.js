#!/usr/bin/env node
/**
 * Copies the repository CHANGELOG.md into docs/Changelog.md before the site
 * starts or builds, so the docs page is never a stale copy. The output is
 * git-ignored. Its front matter sets `mdx.format: md` so it is parsed as CommonMark:
 * the changelog uses autolinks and "<" in prose, which MDX rejects.
 */

const fs = require("fs");
const path = require("path");

const source = path.resolve(__dirname, "../../CHANGELOG.md");
const target = path.resolve(__dirname, "../docs/Changelog.md");

const body = fs
  .readFileSync(source, "utf8")
  // The page title comes from the front matter.
  .replace(/^# Changelog\s*\n/, "");

const frontMatter = [
  "---",
  "id: Changelog",
  "title: Changelog",
  "description: Every release of @devilsdev/rag-pipeline-utils, from CHANGELOG.md in the repository.",
  "mdx:",
  "  format: md",
  "toc_max_heading_level: 2",
  "custom_edit_url: https://github.com/DevilsDev/rag-pipeline-utils/edit/main/CHANGELOG.md",
  "---",
  "",
  "<!-- Generated by scripts/sync-changelog.js from the root CHANGELOG.md. Do not edit. -->",
  "",
].join("\n");

fs.writeFileSync(target, frontMatter + body);
console.log(`[sync-changelog] ${path.relative(process.cwd(), target)}`);
